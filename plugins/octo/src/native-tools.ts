class OctoNativeRuntime {
  #managerStates = new WeakMap<object, ManagerState>();
  #liveManagers = new Set<object>();
  #toolStates = new WeakMap<ToolSession, OctoSessionState>();

  #leases = new WeakMap<AbortSignal, OperationLease>();

  async activateManager(manager: ManagerRef): Promise<void> {
    const key = manager as object;
    const identity = sessionIdentity(manager);
    let state = this.#managerStates.get(key);
    if (!state) {
      state = {
        identity,
        active: true,
        generation: 0,
        controller: new AbortController(),
        sessions: new Set(),
        calls: new Map(),
      };
      this.#managerStates.set(key, state);
      this.#liveManagers.add(key);
      return;
    }
    if (state.identity !== identity) {
      state.active = false;
      state.identity = identity;
      const cleanup = this.#advanceGeneration(state);
      state.cleanup = cleanup;
      await cleanup;
      if (state.cleanup === cleanup) {
        state.cleanup = undefined;
        if (this.#managerStates.get(key) === state && state.identity === identity) state.active = true;
      }
      return;
    }
    if (state.cleanup) {
      const cleanup = state.cleanup;
      await cleanup;
      if (state.cleanup === cleanup) state.cleanup = undefined;
    }
    if (this.#managerStates.get(key) === state && state.identity === identity) state.active = true;
  }

  async resetManager(manager: ManagerRef): Promise<void> {
    const key = manager as object;
    let state = this.#managerStates.get(key);
    if (!state) {
      await this.activateManager(manager);
      state = this.#managerStates.get(key);
      if (!state) return;
    }
    const identity = sessionIdentity(manager);
    state.active = false;
    state.identity = identity;
    const cleanup = this.#advanceGeneration(state);
    state.cleanup = cleanup;
    await cleanup;
    if (state.cleanup === cleanup) {
      state.cleanup = undefined;
      if (this.#managerStates.get(key) === state && state.identity === identity) state.active = true;
    }
  }

  async shutdownManager(manager: ManagerRef): Promise<void> {
    const key = manager as object;
    const state = this.#managerStates.get(key);
    if (!state) return;
    state.active = false;
    const cleanup = this.#advanceGeneration(state);
    this.#managerStates.delete(key);
    this.#liveManagers.delete(key);
    await cleanup;
  }

  async shutdownAll(): Promise<void> {
    const cleanups: Promise<void>[] = [];
    for (const manager of this.#liveManagers) {
      const state = this.#managerStates.get(manager);
      if (state) {
        state.active = false;
        cleanups.push(this.#advanceGeneration(state));
      }
      this.#managerStates.delete(manager);
    }
    this.#liveManagers.clear();
    await Promise.all(cleanups);
  }

  isActive(session: ToolSession): boolean {
    const manager = sessionManagerOf(session);
    if (!manager) return false;
    const state = this.#managerStates.get(manager as object);
    return !!state?.active && !state.cleanup && state.identity === sessionIdentity(manager) && octoEnabled.get(session.settings) === true;
  }

  captureManagerGeneration(manager: ManagerRef): ManagerGeneration | undefined {
    const key = manager as object;
    const state = this.#managerStates.get(key);
    if (!state?.active || state.cleanup || state.identity !== sessionIdentity(manager)) return undefined;
    return { manager: key, managerState: state, generation: state.generation };
  }

  isManagerGenerationCurrent(manager: ManagerRef, ref: ManagerGeneration): boolean {
    return (
      ref.manager === manager &&
      this.#managerStates.get(ref.manager) === ref.managerState &&
      ref.managerState.active &&
      !ref.managerState.cleanup &&
      ref.managerState.generation === ref.generation &&
      ref.managerState.identity === sessionIdentity(manager)
    );
  }

  generationRef(session: ToolSession): GenerationRef {
    if (octoEnabled.get(session.settings) !== true) throw new Error("Octo support is disabled in settings");
    const manager = sessionManagerOf(session);
    if (!manager) throw new Error("Octo tools are not active for this session");
    const key = manager as object;
    const managerState = this.#managerStates.get(key);
    if (
      !managerState?.active ||
      managerState.cleanup ||
      managerState.identity !== sessionIdentity(manager)
    ) {
      throw new Error("Octo tools are not active for this session");
    }
    return { manager: key, managerState, generation: managerState.generation, session };
  }

  assertGeneration(ref: GenerationRef): void {
    if (
      octoEnabled.get(ref.session.settings) !== true ||
      this.#managerStates.get(ref.manager) !== ref.managerState ||
      !ref.managerState.active ||
      ref.managerState.cleanup ||
      ref.managerState.generation !== ref.generation ||
      ref.managerState.identity !== sessionIdentity(ref.manager as ManagerRef)
    ) {
      throw new Error("The active Octo session changed; operation cancelled");
    }
  }

  beginOperation(
    session: ToolSession,
    externalSignal?: AbortSignal,
    expected?: GenerationRef,
  ): OperationLease {
    const ref = expected ?? this.generationRef(session);
    if (ref.session !== session) throw new Error("Octo operation belongs to a different tool session");
    this.assertGeneration(ref);
    if (externalSignal?.aborted) {
      throw externalSignal.reason instanceof Error ? externalSignal.reason : new Error("Octo operation was cancelled");
    }
    const controller = new AbortController();
    const abortFromGeneration = () => controller.abort(ref.managerState.controller.signal.reason);
    const abortFromCaller = () => controller.abort(externalSignal?.reason);
    ref.managerState.controller.signal.addEventListener("abort", abortFromGeneration, { once: true });
    externalSignal?.addEventListener("abort", abortFromCaller, { once: true });
    if (ref.managerState.controller.signal.aborted) abortFromGeneration();
    if (externalSignal?.aborted) abortFromCaller();
    const lease: OperationLease = {
      ...ref,
      signal: controller.signal,
      released: false,
      release: () => {
        lease.released = true;
        ref.managerState.controller.signal.removeEventListener("abort", abortFromGeneration);
        externalSignal?.removeEventListener("abort", abortFromCaller);
      },
    };
    this.#leases.set(lease.signal, lease);
    this.assertCurrent(lease);
    return lease;
  }

  assertCurrent(lease: OperationLease): void {
    if (lease.released) throw new Error("Octo operation has already completed");
    if (lease.signal.aborted) {
      throw lease.signal.reason instanceof Error ? lease.signal.reason : new Error("Octo operation was cancelled");
    }
    this.assertGeneration(lease);
  }

  assertRefCurrent(ref: GenerationRef, signal?: AbortSignal): void {
    const lease = signal ? this.#leases.get(signal) : undefined;
    if (lease) {
      if (lease.session !== ref.session || lease.managerState !== ref.managerState || lease.generation !== ref.generation) {
        throw new Error("Octo operation belongs to a different session generation");
      }
      this.assertCurrent(lease);
      return;
    }
    if (signal?.aborted) {
      throw signal.reason instanceof Error ? signal.reason : new Error("Octo operation was cancelled");
    }
    this.assertGeneration(ref);
  }

  operationForSignal(session: ToolSession, signal?: AbortSignal): OperationLease | undefined {
    if (!signal) return undefined;
    const lease = this.#leases.get(signal);
    if (!lease) return undefined;
    if (lease.session !== session) throw new Error("Octo operation belongs to a different tool session");
    this.assertCurrent(lease);
    return lease;
  }

  async sessionState(session: ToolSession, ref: GenerationRef, signal?: AbortSignal): Promise<OctoSessionState> {
    this.assertRefCurrent(ref, signal);
    const manager = sessionManagerOf(session);
    if (!manager || ref.session !== session || ref.manager !== manager) {
      throw new Error("Octo operation belongs to a different tool session");
    }
    const entry = ref.managerState;
    let state = this.#toolStates.get(session);
    if (state && (
      state.manager !== manager ||
      state.identity !== entry.identity ||
      state.generation !== ref.generation
    )) {
      entry.sessions.delete(state);
      if (this.#toolStates.get(session) === state) this.#toolStates.delete(session);
      void this.#disposeSession(state);
      state = undefined;
    }
    if (!state) {
      state = {
        session,
        manager: manager as object,
        identity: entry.identity,
        generation: ref.generation,
        documents: new Map(),
        readDocuments: new Map(),
        filesById: new Map(),
        idsByFile: new Map(),
        pendingWrites: new Set(),
      };
      this.#toolStates.set(session, state);
      entry.sessions.add(state);
    }
    this.assertRefCurrent(ref, signal);
    return state;
  }

  async pathFor(state: OctoSessionState, document: OctoDocument, ref: GenerationRef, signal?: AbortSignal): Promise<string> {
    this.assertRefCurrent(ref, signal);
    const oldPath = state.filesById.get(document.id);
    const extension = document.type === "html" ? ".html" : ".md";
    if (oldPath && path.extname(oldPath) === extension) return oldPath;
    state.rootPromise ??= mkdtemp(path.join(os.tmpdir(), "omp-octo-native-")).then(root => realpath(root).catch(() => root));
    const root = await state.rootPromise;
    this.assertRefCurrent(ref, signal);
    const filePath = canonicalExistingPath(path.join(root, `${encodeURIComponent(document.id)}${extension}`));
    state.filesById.set(document.id, filePath);
    for (const alias of filePathAliases(filePath)) state.idsByFile.set(alias, document.id);
    return filePath;
  }

  async recordRead(state: OctoSessionState, document: OctoDocument, lease: OperationLease): Promise<string> {
    const filePath = await this.pathFor(state, document, lease, lease.signal);
    await this.#writeFile(state, filePath, document.text, lease);
    this.assertCurrent(lease);
    state.documents.set(document.id, document);
    state.readDocuments.set(document.id, document);
    return filePath;
  }

  async recordWrite(state: OctoSessionState, document: OctoDocument, lease: OperationLease): Promise<string> {
    const filePath = await this.pathFor(state, document, lease, lease.signal);
    await this.#writeFile(state, filePath, document.text, lease);
    this.assertCurrent(lease);
    state.documents.set(document.id, document);
    state.readDocuments.delete(document.id);
    for (const alias of filePathAliases(filePath)) getEditStore(state.session).invalidate(alias);
    return filePath;
  }

  async recordEdit(state: OctoSessionState, document: OctoDocument, lease: OperationLease): Promise<string> {
    const filePath = await this.pathFor(state, document, lease, lease.signal);
    await this.#writeFile(state, filePath, document.text, lease);
    this.assertCurrent(lease);
    state.documents.set(document.id, document);
    state.readDocuments.delete(document.id);
    for (const alias of filePathAliases(filePath)) getEditStore(state.session).invalidate(alias);
    return filePath;
  }

  async #writeFile(state: OctoSessionState, filePath: string, text: string, lease: OperationLease): Promise<void> {
    this.assertCurrent(lease);
    const pending = writeFile(filePath, text, { encoding: "utf8", signal: lease.signal });
    state.pendingWrites.add(pending);
    try {
      await pending;
      this.assertCurrent(lease);
    } finally {
      state.pendingWrites.delete(pending);
    }
  }

  idForFile(session: ToolSession, filePath: string): string | undefined {
    const ids = this.#toolStates.get(session)?.idsByFile;
    if (!ids) return undefined;
    return ids.get(filePath) ?? filePathAliases(filePath).map(alias => ids.get(alias)).find(id => id !== undefined);
  }

  displayPathFor(session: ToolSession, callId: string, canonicalBasePath: string): string {
    const manager = sessionManagerOf(session);
    const state = manager ? this.#managerStates.get(manager as object) : undefined;
    const call = state?.calls.get(callId);
    if (!state || !call || call.managerState !== state || call.generation !== state.generation) return canonicalBasePath;
    for (const [canonical, original] of call.aliases) {
      if (canonicalBasePath === canonical) return original;
      if (canonicalBasePath.startsWith(`${canonical}:`)) return `${original}${canonicalBasePath.slice(canonical.length)}`;
    }
    return canonicalBasePath;
  }

  writeTagFor(session: ToolSession, callId: string | undefined): string | undefined {
    if (!callId) return undefined;
    const manager = sessionManagerOf(session);
    const state = manager ? this.#managerStates.get(manager as object) : undefined;
    const call = state?.calls.get(callId);
    if (!state || !call || call.managerState !== state || call.generation !== state.generation) return undefined;
    return call.writeTag;
  }

  generationForCall(session: ToolSession, callId: string): GenerationRef | undefined {
    if (!callId) return undefined;
    const manager = sessionManagerOf(session);
    if (!manager) return undefined;
    const state = this.#managerStates.get(manager as object);
    const call = state?.calls.get(callId);
    if (!state || !call) return undefined;
    return {
      manager: manager as object,
      managerState: call.managerState,
      generation: call.generation,
      session,
    };
  }

  recordCall(
    manager: ManagerRef,
    callId: string,
    aliases: Map<string, string>,
    writeTag?: string,
    trackGeneration = false,
  ): void {
    const state = this.#managerStates.get(manager as object);
    if (!state || !state.active || state.cleanup) return;
    if (aliases.size === 0 && !writeTag && !trackGeneration) return;
    state.calls.delete(callId);
    state.calls.set(callId, {
      aliases,
      ...(writeTag ? { writeTag } : {}),
      managerState: state,
      generation: state.generation,
    });
    while (state.calls.size > SESSION_MANAGER_CALL_LIMIT) {
      const oldest = state.calls.keys().next().value;
      if (oldest === undefined) break;
      state.calls.delete(oldest);
    }
  }

  finishCall(manager: ManagerRef, callId: string): void {
    this.#managerStates.get(manager as object)?.calls.delete(callId);
  }

  #managerStateFor(manager: ManagerRef): ManagerState | undefined {
    const state = this.#managerStates.get(manager as object);
    return state?.identity === sessionIdentity(manager) ? state : undefined;
  }

  #advanceGeneration(state: ManagerState): Promise<void> {
    state.generation += 1;
    state.controller.abort(new Error("Octo session changed; operation cancelled"));
    state.controller = new AbortController();
    const sessions = [...state.sessions];
    state.sessions.clear();
    return Promise.all(sessions.map(session => this.#disposeSession(session))).then(() => undefined);
  }

  async #disposeSession(state: OctoSessionState): Promise<void> {
    clearEditStreamsForSession(state.session);
    for (const filePath of state.idsByFile.keys()) getEditStore(state.session).invalidate(filePath);
    if (this.#toolStates.get(state.session) === state) this.#toolStates.delete(state.session);
    state.documents.clear();
    state.readDocuments.clear();
    state.filesById.clear();
    state.idsByFile.clear();
    await Promise.allSettled([...state.pendingWrites]);
    if (state.rootPromise) {
      try {
        await rm(await state.rootPromise, { recursive: true, force: true });
      } catch {
        // Cleanup failure must not revive a stale remote edit snapshot.
      }
    }
  }
}


const runtimeSlot = Symbol.for("omp.octo.native-runtime.18.18.7");
const runtimeHost = globalThis as unknown as Record<PropertyKey, unknown>;
const runtime = (runtimeHost[runtimeSlot] as OctoNativeRuntime | undefined) ?? new OctoNativeRuntime();
if (!runtimeHost[runtimeSlot]) Object.defineProperty(runtimeHost, runtimeSlot, { value: runtime });

const octoProtocol: ProtocolHandler = {
  scheme: "octo",
  spec: {
    backing: "remote",
    selectors: "lines",
    immutable: false,
    write: {
      via: "handler",
      payload: "text",
      scope: "workspace",
      tier: (_url, _content, session) =>
        session && runtime.isActive(session)
          ? "write"
          : { tier: "write", policy: "deny", reason: "Octo tools are not active for this session" },
    },
  },
  async resolve(url: InternalUrl, context?: ResolveContext): Promise<InternalResource> {
    const session = context?.session;
    if (!session) throw new Error("Octo read requires an active tool session");
    let lease = runtime.operationForSignal(session, context?.signal);
    const ownedLease = !lease;
    lease ??= runtime.beginOperation(session, context?.signal);
    try {
      runtime.assertCurrent(lease);
      const state = await runtime.sessionState(session, lease);
      const target = targetFromInternalUrl(url);
      if (!target) throw new Error(`Invalid Octo document URL '${url.rawHref ?? url.href}'`);
      const document = await readDocument(target.id, lease.signal);
      runtime.assertCurrent(lease);
      const sourcePath = await runtime.recordRead(state, document, lease);
      return {
        url: target.canonicalBasePath,
        content: document.text,
        contentType: document.type === "doc" ? "text/markdown" : "text/plain",
        size: Buffer.byteLength(document.text, "utf8"),
        sourcePath,
        immutable: false,
      };
    } finally {
      if (ownedLease) lease.release();
    }
  },
  async write(url: InternalUrl, content: string, context?: WriteContext) {
    const session = context?.session;
    const callId = context?.toolCall?.id ?? "";
    const expected = runtime.generationForCall(session, callId);
    let lease = runtime.operationForSignal(session, context?.signal);
    const ownedLease = !lease;
    lease ??= runtime.beginOperation(session, context?.signal, expected);
    try {
      runtime.assertCurrent(lease);
      const state = await runtime.sessionState(session, lease);
      const target = targetFromInternalUrl(url);
      if (!target) throw new Error(`Invalid Octo document URL '${url.rawHref ?? url.href}'`);
      const displayPath = runtime.displayPathFor(session, context?.toolCall?.id ?? "", target.canonicalBasePath);
      const tag = runtime.writeTagFor(session, context?.toolCall?.id);
      let document = state.readDocuments.get(target.id);
      if (tag) {
        const filePath = document ? await runtime.pathFor(state, document, lease, lease.signal) : undefined;
        const currentTag = filePath ? getEditStore(session).headHash(filePath) : null;
        if (!currentTag || currentTag !== tag) {
          throw new Error(`Stale or unseen hashline snapshot for '${displayPath}'; read the document again before writing`);
        }
      }
      document ??= state.documents.get(target.id);
      document ??= await readDocument(target.id, lease.signal);
      runtime.assertCurrent(lease);
      let written: OctoDocument;
      try {
        written = await writeDocument(document, content, lease.signal);
      } catch (error) {
        throw new Error(`Unable to write Octo document '${displayPath}': ${errorText(error)}`);
      }
      try {
        await runtime.recordWrite(state, written, lease);
      } catch (error) {
        throw new Error(
          `Octo document '${displayPath}' was written (version ${written.version}), but its local snapshot could not be refreshed: ${errorText(error)}`,
        );
      }
      return {
        content: [{ type: "text", text: `Wrote Octo document '${displayPath}' (${written.type}, version ${written.version})` }],
      };
    } finally {
      if (ownedLease) lease.release();
    }
  },
};

