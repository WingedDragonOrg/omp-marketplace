function currentEditStreams(tool: EditTool): Map<string, EditStreamState> {
  let streams = editStreams.get(tool);
  if (!streams) {
    streams = new Map();
    editStreams.set(tool, streams);
  }
  return streams;
}

function closeStreamState(state: EditStreamState): void {
  state.nativeStream?.cancel();
  state.remote?.native.close();
  state.chunks.length = 0;
}
function removeEditStream(tool: EditTool, toolCallId: string, expected?: EditStreamState): void {
  const streams = editStreams.get(tool);
  if (!streams || (expected && streams.get(toolCallId) !== expected)) return;
  streams.delete(toolCallId);
  if (streams.size === 0) editStreamTools.delete(tool);
}

function discardEditStream(tool: EditTool, toolCallId: string, state?: EditStreamState): void {
  const streams = editStreams.get(tool);
  const current = streams?.get(toolCallId);
  if (!current || (state && current !== state)) return;
  closeStreamState(current);
  removeEditStream(tool, toolCallId, current);
}

function clearEditStreamsForSession(session: ToolSession): void {
  for (const tool of editStreamTools) {
    if (toolSessionOfEdit(tool) !== session) continue;
    const streams = editStreams.get(tool);
    if (streams) {
      for (const state of streams.values()) closeStreamState(state);
      streams.clear();
      editStreams.delete(tool);
    }
    editStreamTools.delete(tool);
  }
}

function remoteEditPolicy(tool: EditTool, rawInput: boolean, signal?: AbortSignal): EditPolicy {
  const session = toolSessionOfEdit(tool);
  const router = InternalUrlRouter.instance();
  const specs = router.specs();
  const urlSchemes = [...specs.keys()];
  if (!urlSchemes.includes("https")) urlSchemes.push("https");
  const urlAliasSchemes: string[] = [];
  for (const [scheme, spec] of specs) if (spec.singleSlashAlias) urlAliasSchemes.push(scheme);
  const maxColumns = resolveOutputMaxColumns(session.settings);
  return {
    cwd: session.cwd,
    mode: tool.mode,
    allowFuzzy: cfgEditFuzzyMatch.get(session.settings),
    fuzzyThreshold: cfgEditFuzzyThreshold.get(session.settings),
    // Remote hashes are authorization snapshots, regardless of local edit settings.
    enforceSeenLines: true,
    maxColumns: maxColumns > 0 ? Math.min(maxColumns, DEFAULT_MAX_COLUMN) : DEFAULT_MAX_COLUMN,
    blockAutoGenerated: cfgEditBlockAutoGenerated.get(session.settings),
    planActive: session.getPlanModeState?.()?.enabled ?? false,
    urlSchemes,
    urlAliasSchemes,
    planWritableRoots: router.sandboxRoots(sessionResolveContext(session, { signal })),
    homeDir: os.homedir(),
    rawInput,
  };
}

function openRemoteEdit(
  tool: EditTool,
  rawInput: boolean,
  ref: GenerationRef,
  signal: AbortSignal,
  onPreview?: (error: Error | null, batch: EditPreviewBatch) => void,
): RemoteEditOpen {
  const session = toolSessionOfEdit(tool);
  const state = { resolveContext: sessionResolveContext(session, { signal }) } as RemoteEditOpen;
  const native = new EditSession(
    getEditStore(session),
    remoteEditPolicy(tool, rawInput, signal),
    onPreview,
    async (_error, url): Promise<EditUrlResolution> => {
      const parsed = parseDocumentPath(url);
      if (parsed.kind === "invalid") return { error: parsed.message, planWritable: false };
      if (parsed.kind !== "octo") return { error: `Not an Octo document path: '${url}'`, planWritable: false };
      if (parsed.target.selector) return { error: `Hashline edits must target the whole Octo document: '${url}'`, planWritable: false };
      try {
        runtime.assertRefCurrent(ref, signal);
        const sessionState = await runtime.sessionState(session, ref, signal);
        const document = sessionState.readDocuments.get(parsed.target.id);
        if (!document) return { error: `Read Octo document '${url}' before editing it`, planWritable: false };
        const filePath = await runtime.pathFor(sessionState, document, ref, signal);
        runtime.assertRefCurrent(ref, signal);
        // EditSession has only filesystem sandbox roots; applyRemoteEdit and its writer
        // re-run the native plan guard for every Octo target before its mutation.
        return { path: filePath, planWritable: true };
      } catch (error) {
        return { error: errorText(error), planWritable: false };
      }
    },
  );
  state.native = native;
  return state;
}

function readOutputForOcto(result: NativeResult, filePath: string | undefined, displayPath: string, cwd: string): NativeResult {
  const content = result.content.map(block => ({ ...block }));
  const first = content.find(block => block.type === "text" && typeof block.text === "string");
  let emittedPath = false;
  if (first && typeof first.text === "string") {
    const newline = first.text.indexOf("\n");
    const headerLine = newline < 0 ? first.text : first.text.slice(0, newline);
    const header = /^\[([^\]]+)#([0-9a-f]{4})\]$/i.exec(headerLine);
    if (header && (!filePath || sameFilesystemPath(header[1]!, filePath, cwd))) {
      first.text = `[${displayPath}#${header[2]}]${newline < 0 ? "" : first.text.slice(newline)}`;
      emittedPath = true;
    }
    if (result.isError && !first.text.includes(displayPath)) {
      first.text = `Unable to read Octo document '${displayPath}': ${first.text}`;
      emittedPath = true;
    }
  }
  if (!emittedPath && !result.isError) content.unshift({ type: "text", text: `Octo source: ${displayPath}` });
  const details = result.details && typeof result.details === "object" ? { ...(result.details as Record<string, unknown>) } : {};
  details.resolvedPath = displayPath;
  return { ...result, content, details };
}

function recordOctoReadSeenLines(session: ToolSession, filePath: string | undefined, result: NativeResult): void {
  if (!filePath || result.isError) return;
  const first = result.content.find(block => block.type === "text" && typeof block.text === "string");
  if (!first || typeof first.text !== "string") return;
  const newline = first.text.indexOf("\n");
  const headerLine = newline < 0 ? first.text : first.text.slice(0, newline);
  const header = /^\[([^\]]+)#([0-9a-f]{4})\]$/i.exec(headerLine);
  if (!header) return;

  let lines: number[] = [];
  const details = result.details;
  if (details && typeof details === "object" && "displayContent" in details) {
    const displayContent = details.displayContent;
    if (
      displayContent &&
      typeof displayContent === "object" &&
      "lineNumbers" in displayContent &&
      Array.isArray(displayContent.lineNumbers)
    ) {
      lines = displayContent.lineNumbers.filter(
        (line: unknown): line is number => typeof line === "number" && Number.isInteger(line) && line > 0,
      );
    }
  }
  // Zero records that provenance exists even when no complete row was rendered.
  getEditStore(session).recordSeenLines(filePath, header[2]!.toUpperCase(), lines.length > 0 ? lines : [0]);
}


const patchedReadExecute: typeof ReadTool.prototype.execute = async function (
  this: ReadTool,
  toolCallId,
  params,
  signal,
  onUpdate,
  context,
) {
  const session = toolSessionOfRead(this);
  const rawPath = typeof params.path === "string" ? params.path : "";
  const parsed = parseDocumentPath(rawPath);
  if (parsed.kind === "other") {
    return nativeReadExecute.call(this, toolCallId, params, signal, onUpdate, context);
  }
  if (parsed.kind === "invalid") return toolError(parsed.message) as Awaited<ReturnType<typeof nativeReadExecute>>;
  if (parsed.target.source === "https") {
    return toolError(`HTTPS Octo URL '${rawPath}' must be normalized before native approval`) as Awaited<ReturnType<typeof nativeReadExecute>>;
  }
  if (!runtime.isActive(session)) {
    return toolError("Octo tools are not active for this session") as Awaited<ReturnType<typeof nativeReadExecute>>;
  }

  const displayPath = runtime.displayPathFor(session, toolCallId, parsed.target.canonicalBasePath);
  let lease: OperationLease | undefined;
  try {
    lease = runtime.beginOperation(session, signal, runtime.generationForCall(session, toolCallId));
    const result = await nativeReadExecute.call(this, toolCallId, params, lease.signal, onUpdate, context) as NativeResult;
    runtime.assertCurrent(lease);
    const state = await runtime.sessionState(session, lease);
    const filePath = state.filesById.get(parsed.target.id);
    recordOctoReadSeenLines(session, filePath, result);
    return readOutputForOcto(result, filePath, displayPath, session.cwd) as Awaited<ReturnType<typeof nativeReadExecute>>;
  } catch (error) {
    return toolError(`Unable to read Octo document '${displayPath}': ${errorText(error)}`) as Awaited<ReturnType<typeof nativeReadExecute>>;
  } finally {
    lease?.release();
  }
};

function createRemoteStreamState(tool: EditTool, init: AgentToolArgStreamInit, generation: GenerationRef): EditStreamState {
  const state: EditStreamState = { tool, init, chunks: [], branch: "pending", generation };
  editStreamTools.add(tool);
  currentEditStreams(tool).set(init.toolCallId, state);
  return state;
}

function selectStreamBranch(state: EditStreamState, args?: unknown): void {
  if (state.branch !== "pending" || args === undefined) return;
  const rawInput = typeof args === "string" ? args : inputString(args);
  if (remoteStreamTarget(state.chunks, args)) {
    state.branch = state.tool.mode === "hashline" ? "remote" : "unsupported";
    if (state.branch === "remote") {
      const parsed = rawInput ? remoteSectionsFor(rawInput) : undefined;
      const remoteInput = parsed?.remote.length
        ? [...parsed.parsed.prefix, ...parsed.remote.flatMap(section => section.lines), ...parsed.parsed.suffix].join("\n")
        : rawInput || state.chunks.join("");
      const rawMode = state.init.customWireName !== undefined;
      const params = typeof args === "object" && args !== null ? { ...(args as Record<string, unknown>) } : {};
      params.input = remoteInput;
      delete params.path;
      delete params.paths;
      const remoteArgs = JSON.stringify(params);
      if (!state.generation) {
        state.branch = "unsupported";
        return;
      }
      state.remote = openRemoteEdit(
        state.tool,
        rawMode,
        state.generation,
        state.generation.managerState.controller.signal,
        (error, batch) => {
          if (!error) state.init.emit(batch);
        },
      );
      if (rawMode) state.remote.native.push(remoteInput);
      else state.remote.native.setArgsJson(remoteArgs);
      state.remote.native.finish();
      state.remote.argsJson = remoteArgs;
      state.argsJson = remoteArgs;
      if (parsed?.local.length) {
        const localInput = [...parsed.parsed.prefix, ...parsed.local.flatMap(section => section.lines), ...parsed.parsed.suffix].join("\n");
        const localParams = typeof args === "object" && args !== null ? { ...(args as Record<string, unknown>) } : {};
        localParams.input = localInput;
        delete localParams.path;
        delete localParams.paths;
        state.nativeStream = nativeEditOpenArgStream.call(state.tool, state.init);
        if (rawMode) state.nativeStream.push(localInput);
        else state.nativeStream.push(JSON.stringify(localParams));
        state.nativeStream.end(localParams);
      }
    }
    state.chunks.length = 0;
    return;
  }
  state.branch = "native";
  state.nativeStream = nativeEditOpenArgStream.call(state.tool, state.init);
  for (const chunk of state.chunks) state.nativeStream.push(chunk);
  state.chunks.length = 0;
  state.nativeStream.end(args);
  state.argsJson = JSON.stringify(args);
}

const patchedEditOpenArgStream: typeof EditTool.prototype.openArgStream = function (
  this: EditTool,
  init,
) {
  const session = toolSessionOfEdit(this);
  if (!runtime.isActive(session)) return nativeEditOpenArgStream.call(this, init);
  let generation: GenerationRef;
  try {
    generation = runtime.generationRef(session);
  } catch {
    return nativeEditOpenArgStream.call(this, init);
  }
  const streams = currentEditStreams(this);
  const previous = streams.get(init.toolCallId);
  if (previous) closeStreamState(previous);
  const state = createRemoteStreamState(this, init, generation);
  return {
    push(delta: string) {
      if (state.branch === "pending") state.chunks.push(delta);
    },
    end(args: unknown) {
      selectStreamBranch(state, args);
      state.argsJson = JSON.stringify(args);
    },
    cancel() {
      discardEditStream(state.tool, init.toolCallId, state);
    },
  };
};

function remoteSectionsFor(input: string): { parsed: HashlineSections; local: HashlineSection[]; remote: HashlineSection[] } | undefined {
  const parsed = hashlineSections(input);
  if (!parsed) return undefined;
  const local: HashlineSection[] = [];
  const remote: HashlineSection[] = [];
  for (const section of parsed.sections) {
    const target = parseDocumentPath(section.path);
    if (target.kind === "octo" || target.kind === "invalid" && isOctoLikePath(section.path)) remote.push(section);
    else local.push(section);
  }
  return { parsed, local, remote };
}

function mapTempPaths(text: string, state: OctoSessionState, session: ToolSession, toolCallId: string): string {
  let result = text;
  for (const [id, filePath] of state.filesById) {
    const canonical = `octo://${encodeURIComponent(id)}`;
    const displayPath = runtime.displayPathFor(session, toolCallId, canonical);
    for (const alias of filePathAliases(filePath)) result = result.replaceAll(alias, displayPath);
    result = result.replaceAll(canonical, displayPath);
  }
  return result;
}

async function applyRemoteEdit(
  tool: EditTool,
  toolCallId: string,
  input: string,
  lease: OperationLease,
  streamed: EditStreamState | undefined,
): Promise<NativeResult> {
  const session = toolSessionOfEdit(tool);
  const discardStream = (): void => {
    if (streamed) discardEditStream(tool, toolCallId, streamed);
  };
  try {
    runtime.assertCurrent(lease);
  } catch (error) {
    discardStream();
    return toolError(`Octo edit is unavailable for this session: ${errorText(error)}`);
  }
  if (session.deviceOnlyWrite === true) {
    discardStream();
    return toolError("Octo edits are unavailable when write is device-only");
  }
  const sections = hashlineSections(input);
  if (!sections) {
    discardStream();
    return toolError("Octo edits require hashline mode and a recent read snapshot");
  }
  const remoteTargets = sections.sections.map(section => parseDocumentPath(section.path));
  for (const target of remoteTargets) {
    if (target.kind === "invalid") {
      discardStream();
      return toolError(target.message);
    }
    if (target.kind !== "octo") {
      discardStream();
      return toolError("Octo edits require hashline mode and a recent read snapshot");
    }
    if (target.target.selector) {
      discardStream();
      return toolError(`Hashline edits must target the whole Octo document: '${target.target.originalPath}'`);
    }
  }

  try {
    for (const target of remoteTargets) {
      if (target.kind === "octo") {
        await enforcePlanModeWrite(session, target.target.canonicalBasePath, { op: "update", signal: lease.signal });
        runtime.assertCurrent(lease);
      }
    }
  } catch (error) {
    discardStream();
    return toolError(errorText(error));
  }

  let state: OctoSessionState;
  try {
    state = await runtime.sessionState(session, lease);
  } catch (error) {
    discardStream();
    return toolError(`Octo edit is unavailable for this session: ${errorText(error)}`);
  }

  const remoteInput = [...sections.prefix, ...sections.sections.flatMap(section => section.lines), ...sections.suffix].join("\n");
  const argsJson = JSON.stringify({ input: remoteInput });
  discardStream();
  const open = openRemoteEdit(tool, false, lease, lease.signal);
  open.native.setArgsJson(argsJson);
  open.native.finish();

  const committed = new Set<string>();
  const uncertain = new Set<string>();
  let outcome: EditApplyOutcome;
  try {
    outcome = await open.native.apply({ lspFlush: false }, async (error, request: EditWriteRequest) => {
      if (error) throw error;
      runtime.assertCurrent(lease);
      if (request.op !== "update" || request.content === undefined) {
        throw new Error(`Octo documents cannot be ${request.op === "delete" ? "deleted" : request.op === "move" ? "renamed" : "created"}`);
      }
      const id = runtime.idForFile(session, request.path);
      const document = id ? state.readDocuments.get(id) : undefined;
      if (!id || !document) throw new Error(`No read snapshot is available for '${request.displayPath}'`);
      const canonicalPath = `octo://${encodeURIComponent(id)}`;
      await enforcePlanModeWrite(session, canonicalPath, { op: "update", signal: lease.signal });
      runtime.assertCurrent(lease);
      let written: OctoDocument;
      try {
        written = await writeDocument(document, request.content, lease.signal);
      } catch (writeError) {
        if (/write may have been written/i.test(errorText(writeError))) uncertain.add(id);
        throw writeError;
      }
      committed.add(id);
      await runtime.recordEdit(state, written, lease);
      return { written: written.text };
    });
  } catch (error) {
    const committedPaths = [...committed.keys()].map(id =>
      runtime.displayPathFor(session, toolCallId, `octo://${encodeURIComponent(id)}`),
    );
    const uncertainPaths = [...uncertain.keys()].map(id =>
      runtime.displayPathFor(session, toolCallId, `octo://${encodeURIComponent(id)}`),
    );
    const failure = mapTempPaths(errorText(error), state, session, toolCallId);
    const statuses = [
      committedPaths.length > 0 ? `confirmed committed: ${committedPaths.join(", ")}` : "",
      uncertainPaths.length > 0 ? `submission outcome uncertain: ${uncertainPaths.join(", ")}` : "",
    ].filter(Boolean);
    const message = statuses.length > 0
      ? `Octo edit stopped (${statuses.join("; ")}); later operation failed: ${failure}`
      : `Octo edit failed: ${failure}`;
    return {
      content: [{ type: "text", text: message }],
      details: {
        committedDocuments: [...committed.keys()],
        committedPaths,
        uncertainDocuments: [...uncertain.keys()],
        uncertainPaths,
      },
      isError: true,
    };
  } finally {
    open.native.close();
  }

  const displayPaths = [...new Set(remoteTargets.flatMap(target =>
    target.kind === "octo"
      ? [runtime.displayPathFor(session, toolCallId, target.target.canonicalBasePath)]
      : [],
  ))];
  let text = mapTempPaths(outcome.text || outcome.files.map(file => file.text).join("\n"), state, session, toolCallId);
  if (displayPaths.length > 0) {
    text = `Octo edit ${outcome.isError ? "partially applied or failed" : "completed"} for: ${displayPaths.join(", ")}\n${text}`;
  }
  const details = {
    files: outcome.files.map(file => {
      const id = runtime.idForFile(session, file.path);
      const canonical = id ? `octo://${encodeURIComponent(id)}` : file.displayPath;
      return {
        path: runtime.displayPathFor(session, toolCallId, canonical),
        operation: file.op,
        diff: file.diff,
      };
    }),
    committedDocuments: [...committed.keys()],
    ...(outcome.errorKind ? { errorKind: outcome.errorKind } : {}),
  };
  return {
    content: [{ type: "text", text }],
    details,
    ...(outcome.isError ? { isError: true } : {}),
  };
}

function nativeToolParamsForSections(params: Record<string, unknown>, input: string): Record<string, unknown> {
  return { ...params, input };
}

const patchedEditExecute: typeof EditTool.prototype.execute = async function (
  this: EditTool,
  toolCallId,
  params,
  signal,
  onUpdate,
  context,
) {
  const session = toolSessionOfEdit(this);
  const streamed = editStreams.get(this)?.get(toolCallId);
  const input = inputString(params);
  const directPath = pathString(params);
  const directTarget = directPath ? parseDocumentPath(unwrapWritePath(directPath).path) : { kind: "other" as const };
  const parsedSections = input ? remoteSectionsFor(input) : undefined;
  const hasRemoteSections = !!parsedSections?.remote.length;
  const nonHashlineTarget = input ? hasNonHashlineOctoFileTarget(input) : false;
  const hasRemoteDirectPath = directTarget.kind === "octo" || directTarget.kind === "invalid" && isOctoLikePath(directPath);
  const hasRemoteTarget = hasRemoteSections || nonHashlineTarget || hasRemoteDirectPath;

  if (!hasRemoteTarget) {
    if (streamed) {
      if (streamed.branch === "remote" || streamed.branch === "unsupported") discardEditStream(this, toolCallId, streamed);
      else removeEditStream(this, toolCallId, streamed);
    }
    return nativeEditExecute.call(this, toolCallId, params, signal, onUpdate, context);
  }
  if (!runtime.isActive(session)) {
    if (streamed) discardEditStream(this, toolCallId, streamed);
    return toolError("Octo tools are not active for this session") as Awaited<ReturnType<typeof nativeEditExecute>>;
  }

  if (this.mode !== "hashline") {
    if (streamed) discardEditStream(this, toolCallId, streamed);
    return toolError("Octo edits require hashline mode and a recent read snapshot") as Awaited<ReturnType<typeof nativeEditExecute>>;
  }
  if (nonHashlineTarget || !parsedSections || !hasRemoteSections) {
    if (streamed) discardEditStream(this, toolCallId, streamed);
    return toolError("Octo edits require hashline mode and a recent read snapshot") as Awaited<ReturnType<typeof nativeEditExecute>>;
  }

  let lease: OperationLease;
  try {
    lease = runtime.beginOperation(
      session,
      signal,
      streamed?.generation ?? runtime.generationForCall(session, toolCallId),
    );
  } catch (error) {
    if (streamed) discardEditStream(this, toolCallId, streamed);
    return toolError(`Octo edit is unavailable for this session: ${errorText(error)}`) as Awaited<ReturnType<typeof nativeEditExecute>>;
  }
  try {
    if (parsedSections.local.length === 0) {
      return await applyRemoteEdit(this, toolCallId, input, lease, streamed) as Awaited<ReturnType<typeof nativeEditExecute>>;
    }

    const completedTargets: string[] = [];
    const completedTargetSet = new Set<string>();
    const uncertainTargets: string[] = [];
    const uncertainTargetSet = new Set<string>();
    const results: Array<{ target: string; domain: "local" | "octo"; result: NativeResult }> = [];
    const addCompletedTarget = (target: string): void => {
      if (completedTargetSet.has(target)) return;
      completedTargetSet.add(target);
      completedTargets.push(target);
    };
    const addUncertainTarget = (target: string): void => {
      if (uncertainTargetSet.has(target)) return;
      uncertainTargetSet.add(target);
      uncertainTargets.push(target);
    };

    // Native EditTool and remote EditSession share the session EditStore, so
    // CUT/PUT registers survive ordered section execution across domains.
    // Re-open each section so previews cannot bind a grouped, differently ordered patch.
    if (streamed) discardEditStream(this, toolCallId, streamed);

    for (const section of parsedSections.parsed.sections) {
      const target = parseDocumentPath(section.path);
      const isRemote = target.kind === "octo" || target.kind === "invalid" && isOctoLikePath(section.path);
      const displayPath = target.kind === "octo"
        ? runtime.displayPathFor(session, toolCallId, target.target.canonicalBasePath)
        : section.path;
      const sectionInput = [...parsedSections.parsed.prefix, ...section.lines, ...parsedSections.parsed.suffix].join("\n");
      let result: NativeResult;
      let operationError: string | undefined;
      try {
        runtime.assertCurrent(lease);
      } catch (error) {
        operationError = errorText(error);
      }

      if (operationError) {
        result = toolError(`Mixed edit was cancelled before submission: ${operationError}`);
      } else if (isRemote) {
        result = await applyRemoteEdit(this, toolCallId, sectionInput, lease, undefined);
        const details = typeof result.details === "object" && result.details !== null
          ? result.details as { committedDocuments?: unknown; uncertainPaths?: unknown }
          : undefined;
        if (Array.isArray(details?.committedDocuments)) {
          for (const id of details.committedDocuments) {
            if (typeof id !== "string") continue;
            addCompletedTarget(runtime.displayPathFor(session, toolCallId, `octo://${encodeURIComponent(id)}`));
          }
        }
        if (Array.isArray(details?.uncertainPaths)) {
          for (const targetPath of details.uncertainPaths) {
            if (typeof targetPath === "string") addUncertainTarget(targetPath);
          }
        }
        if (!result.isError) addCompletedTarget(displayPath);
      } else {
        try {
          result = await nativeEditExecute.call(
            this,
            toolCallId,
            nativeToolParamsForSections(params as unknown as Record<string, unknown>, sectionInput) as typeof params,
            lease.signal,
            onUpdate,
            context,
          ) as NativeResult;
        } catch (error) {
          result = toolError(`Native edit failed: ${errorText(error)}`);
        }
        if (!result.isError) addCompletedTarget(displayPath);
      }

      results.push({ target: displayPath, domain: isRemote ? "octo" : "local", result });
      if (result.isError) {
        const completed = completedTargets.length > 0 ? completedTargets.join(", ") : "none";
        const uncertain = uncertainTargets.length > 0 ? uncertainTargets.join(", ") : "none";
        const failure = result.content
          .filter((block): block is { type: string; text: string } => typeof block.text === "string")
          .map(block => block.text)
          .join("\n") || "Edit failed without details";
        return {
          content: [
            {
              type: "text",
              text:
                `Mixed edit stopped at '${displayPath}'.\n` +
                `Confirmed completed targets in patch order (including any confirmed commit from the failing operation): ${completed}.\n` +
                `Targets with uncertain submission outcome: ${uncertain}.\n` +
                failure,
            },
            ...results.slice(0, -1).flatMap(entry => entry.result.content),
          ],
          details: {
            completedTargets,
            uncertainTargets,
            failedTarget: displayPath,
            operations: results.map(({ target: operationTarget, domain, result: operationResult }) => ({
              target: operationTarget,
              domain,
              isError: !!operationResult.isError,
              details: operationResult.details,
            })),
          },
          isError: true,
        } as Awaited<ReturnType<typeof nativeEditExecute>>;
      }
    }

    return {
      content: [
        { type: "text", text: `Mixed edit completed in patch order for: ${completedTargets.join(", ")}` },
        ...results.flatMap(entry => entry.result.content),
      ],
      details: {
        completedTargets,
        uncertainTargets,
        operations: results.map(({ target: operationTarget, domain, result: operationResult }) => ({
          target: operationTarget,
          domain,
          isError: !!operationResult.isError,
          details: operationResult.details,
        })),
      },
    } as Awaited<ReturnType<typeof nativeEditExecute>>;
  } finally {
    lease.release();
  }
};

function normalizedInputForToolCall(event: { toolName: string; input: unknown }, aliases: Map<string, string>): { input?: Record<string, unknown>; error?: string; writeTag?: string } {
  const params = typeof event.input === "object" && event.input !== null ? event.input as Record<string, unknown> : {};
  const next: Record<string, unknown> = { ...params };
  let changed = false;
  let writeTag: string | undefined;
  if (event.toolName === "read" || event.toolName === "write") {
    const rawPath = typeof params.path === "string" ? params.path : undefined;
    if (!rawPath) return {};
    const rewritten = replaceHttpPath(rawPath, aliases, event.toolName === "read", event.toolName === "write");
    if (rewritten.error) return { error: rewritten.error };
    if (rewritten.path !== rawPath) {
      next.path = rewritten.path;
      changed = true;
    }
    writeTag = event.toolName === "write" ? rewritten.tag : undefined;
  } else if (event.toolName === "edit") {
    const rawPath = typeof params.path === "string" ? params.path : undefined;
    if (rawPath) {
      const rewritten = replaceHttpPath(rawPath, aliases, false);
      if (rewritten.error) return { error: rewritten.error };
      if (rewritten.path !== rawPath) {
        next.path = rewritten.path;
        changed = true;
      }
    }
    for (const key of ["input", "_input"] as const) {
      const rawInput = typeof params[key] === "string" ? (params[key] as string) : undefined;
      if (!rawInput) continue;
      const rewritten = rewriteHashlineInput(rawInput, aliases);
      if (rewritten.error) return { error: rewritten.error };
      if (rewritten.input !== rawInput) {
        next[key] = rewritten.input;
        changed = true;
      }
    }
    // Hashline compatibility fields are derived for approval only, not real tool parameters.
    if (Array.isArray(params.paths)) {
      delete next.paths;
      delete next.path;
      changed = true;
    }
  }
  return { ...(changed ? { input: next } : {}), ...(writeTag ? { writeTag } : {}) };
}

const UNWRAPPED_EXECUTE = "OutputMeta.UnwrappedExecute";

type HeldPatch = {
  symbol?: symbol;
  originalExecute?: Function;
  patchedExecute?: Function;
  openArgStream?: PropertyDescriptor;
  patchedOpen?: Function;
};

const heldPatches = new WeakMap<object, HeldPatch>();
const heldByManager = new WeakMap<object, Set<object>>();

function trackHeld(manager: object, instance: object): void {
  let instances = heldByManager.get(manager);
  if (!instances) {
    instances = new Set();
    heldByManager.set(manager, instances);
  }
  instances.add(instance);
}

function unwrappedExecuteSymbol(instance: object): symbol | undefined {
  const symbols = Object.getOwnPropertySymbols(instance).filter(symbol => symbol.description === UNWRAPPED_EXECUTE);
  return symbols.length === 1 ? symbols[0] : undefined;
}

function sessionManagerOfTool(instance: object): object | undefined {
  if (!("session" in instance)) return undefined;
  const session = instance.session;
  if (!session || typeof session !== "object" || !("sessionManager" in session)) return undefined;
  const manager = session.sessionManager;
  return manager && typeof manager === "object" ? manager : undefined;
}

function bindCapturedExecute(instance: object, patched: Function, manager: object, name: string): void {
  const symbol = unwrappedExecuteSymbol(instance);
  if (!symbol) {
    throw new Error(`Octo cannot bind native ${name}: expected exactly one OutputMeta.UnwrappedExecute symbol`);
  }
  const descriptor = Object.getOwnPropertyDescriptor(instance, symbol);
  if (!descriptor?.configurable || typeof descriptor.value !== "function") {
    throw new Error(`Octo cannot bind native ${name}: OutputMeta.UnwrappedExecute is not a configurable function`);
  }
  const record = heldPatches.get(instance) ?? {};
  if (descriptor.value !== patched) {
    if (record.originalExecute === undefined) record.originalExecute = descriptor.value;
    else if (descriptor.value !== record.patchedExecute) {
      throw new Error(`Octo cannot bind native ${name}: OutputMeta.UnwrappedExecute is no longer held by this plugin`);
    }
    Object.defineProperty(instance, symbol, { ...descriptor, value: patched });
  }
  const bound = Object.getOwnPropertyDescriptor(instance, symbol);
  if (bound?.value !== patched) {
    throw new Error(`Octo cannot bind native ${name}: OutputMeta.UnwrappedExecute replacement did not stick`);
  }
  record.symbol = symbol;
  record.patchedExecute = patched;
  heldPatches.set(instance, record);
  trackHeld(manager, instance);
}

function bindCapturedOpenArgStream(instance: object, manager: object): void {
  const own = Object.getOwnPropertyDescriptor(instance, "openArgStream");
  if (own && (!own.configurable || typeof own.value !== "function")) {
    throw new Error("Octo cannot bind native edit: openArgStream is not a configurable function");
  }
  const record = heldPatches.get(instance) ?? {};
  if (own?.value === patchedEditOpenArgStream) {
    record.patchedOpen = patchedEditOpenArgStream;
    heldPatches.set(instance, record);
    trackHeld(manager, instance);
    return;
  }
  if (own && record.patchedOpen && own.value !== record.patchedOpen) {
    throw new Error("Octo cannot bind native edit: openArgStream is no longer held by this plugin");
  }
  if (!record.openArgStream && own) record.openArgStream = own;
  Object.defineProperty(instance, "openArgStream", {
    value: patchedEditOpenArgStream,
    writable: true,
    configurable: true,
    enumerable: own?.enumerable ?? false,
  });
  if (Object.getOwnPropertyDescriptor(instance, "openArgStream")?.value !== patchedEditOpenArgStream) {
    throw new Error("Octo cannot bind native edit: openArgStream replacement did not stick");
  }
  record.patchedOpen = patchedEditOpenArgStream;
  heldPatches.set(instance, record);
  trackHeld(manager, instance);
}

function restoreHeldInstance(instance: object): void {
  const record = heldPatches.get(instance);
  if (!record) return;
  if (record.symbol && record.patchedExecute && record.originalExecute) {
    const descriptor = Object.getOwnPropertyDescriptor(instance, record.symbol);
    if (descriptor?.configurable && descriptor.value === record.patchedExecute) {
      Object.defineProperty(instance, record.symbol, { ...descriptor, value: record.originalExecute });
    }
  }
  if (record.patchedOpen) {
    const own = Object.getOwnPropertyDescriptor(instance, "openArgStream");
    if (own?.configurable && own.value === record.patchedOpen) {
      if (record.openArgStream) Object.defineProperty(instance, "openArgStream", record.openArgStream);
      else Reflect.deleteProperty(instance, "openArgStream");
    }
  }
  heldPatches.delete(instance);
}

function restoreManagerTools(manager: object): void {
  const instances = heldByManager.get(manager);
  if (!instances) return;
  for (const instance of instances) restoreHeldInstance(instance);
  heldByManager.delete(manager);
}

function captureSessionTools(pi: Pick<ExtensionAPI, "getAllTools">, manager: object): void {
  const targets = [
    { name: "read", proto: ReadTool.prototype },
    { name: "edit", proto: EditTool.prototype },
  ] as const;
  const saved: Array<{ name: "read" | "edit"; proto: object; descriptor: PropertyDescriptor & { get: () => string } }> = [];
  const uncapturable: string[] = [];
  for (const target of targets) {
    const descriptor = Object.getOwnPropertyDescriptor(target.proto, "description");
    if (!descriptor?.get || !descriptor.configurable) {
      uncapturable.push(target.name);
      continue;
    }
    saved.push({ name: target.name, proto: target.proto, descriptor });
  }
  const seen = new Set<object>();
  let listingError: unknown;
  let tools: ReturnType<ExtensionAPI["getAllTools"]> = [];
  try {
    for (const { proto, descriptor } of saved) {
      const originalGet = descriptor.get;
      Object.defineProperty(proto, "description", {
        configurable: true,
        enumerable: descriptor.enumerable,
        get() {
          seen.add(this);
          return originalGet.call(this);
        },
      });
    }
    try {
      tools = pi.getAllTools();
    } catch (error) {
      listingError = error;
    }
  } finally {
    for (const { proto, descriptor } of saved) Object.defineProperty(proto, "description", descriptor);
  }
  if (listingError) throw new Error(`Octo cannot inspect native tools: ${errorText(listingError)}`);
  const required = new Set(
    tools
      .filter(tool => (tool.name === "read" || tool.name === "edit") && tool.sourceInfo.source === "builtin")
      .map(tool => tool.name),
  );
  for (const name of uncapturable) {
    if (required.has(name)) {
      throw new Error(`Octo cannot bind native ${name}: description getter is not a configurable prototype getter`);
    }
  }
  let boundRead = false;
  let boundEdit = false;
  for (const instance of seen) {
    const owner = sessionManagerOfTool(instance);
    if (owner && owner !== manager) continue;
    if (instance instanceof ReadTool) {
      bindCapturedExecute(instance, patchedReadExecute, manager, "read");
      boundRead = true;
    }
    if (instance instanceof EditTool) {
      bindCapturedExecute(instance, patchedEditExecute, manager, "edit");
      bindCapturedOpenArgStream(instance, manager);
      boundEdit = true;
    }
  }
  if (required.has("read") && !boundRead) {
    throw new Error("Octo found builtin read but did not bind its captured execute");
  }
  if (required.has("edit") && !boundEdit) {
    throw new Error("Octo found builtin edit but did not bind its captured execute");
  }
}

export function installNativeOctoTools(pi: ExtensionAPI): void {
  InternalUrlRouter.instance().register(octoProtocol);

  pi.on("session_start", async (_event, context) => {
    captureSessionTools(pi, context.sessionManager);
    await runtime.activateManager(context.sessionManager);
  });
  pi.on("session_switch", async (_event, context) => {
    const reset = runtime.resetManager(context.sessionManager);
    try {
      restoreManagerTools(context.sessionManager);
      captureSessionTools(pi, context.sessionManager);
    } finally {
      await reset;
    }
  });
  pi.on("session_shutdown", async (_event, context) => {
    const shutdown = runtime.shutdownManager(context.sessionManager);
    try {
      restoreManagerTools(context.sessionManager);
    } finally {
      await shutdown;
    }
  });
  pi.on("before_agent_start", async (event, context) => {
    captureSessionTools(pi, context.sessionManager);
    await runtime.activateManager(context.sessionManager);
    for (const instance of heldByManager.get(context.sessionManager) ?? []) {
      if (instance instanceof ReadTool && octoEnabled.get(toolSessionOfRead(instance).settings) !== true) return;
    }
    return event.systemPrompt.includes(EXTENSION_SESSION_PROMPT)
      ? undefined
      : { systemPrompt: [...event.systemPrompt, EXTENSION_SESSION_PROMPT] };
  });
  pi.on("tool_call", async (event, context) => {
    const generationAtCall = runtime.captureManagerGeneration(context.sessionManager);
    captureSessionTools(pi, context.sessionManager);
    await runtime.activateManager(context.sessionManager);
    if (event.toolName !== "read" && event.toolName !== "write" && event.toolName !== "edit") return;
    const aliases = new Map<string, string>();
    const rewritten = normalizedInputForToolCall(event, aliases);
    if (rewritten.error) return { block: true, reason: rewritten.error };
    const rawPath = pathString(event.input);
    const remoteCall =
      aliases.size > 0 ||
      !!rewritten.writeTag ||
      (rawPath !== "" && isOctoLikePath(unwrapWritePath(rawPath).path)) ||
      (event.toolName === "edit" && hasRemoteTargetInInput(inputString(event.input)));
    if (remoteCall && generationAtCall && !runtime.isManagerGenerationCurrent(context.sessionManager, generationAtCall)) {
      return { block: true, reason: "Octo tool call belongs to a previous session generation" };
    }
    runtime.recordCall(context.sessionManager, event.toolCallId, aliases, rewritten.writeTag, remoteCall);
    return rewritten.input ? { input: rewritten.input } : undefined;
  });
  pi.on("tool_result", (event, context) => {
    if (event.toolName === "read" || event.toolName === "write" || event.toolName === "edit") {
      runtime.finishCall(context.sessionManager, event.toolCallId);
    }
  });
}
