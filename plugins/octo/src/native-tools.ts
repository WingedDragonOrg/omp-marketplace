const editStreams = new WeakMap<EditTool, Map<string, EditStreamState>>();

function currentEditStreams(tool: EditTool): Map<string, EditStreamState> {
  let streams = editStreams.get(tool);
  if (!streams) {
    streams = new Map();
    editStreams.set(tool, streams);
  }
  return streams;
}

function closeStreamState(state: EditStreamState): void {
  state.nativeStream?.cancel();
  state.remote?.native.close();
  state.chunks.length = 0;
}

function remoteEditPolicy(tool: EditTool, rawInput: boolean, signal?: AbortSignal): EditPolicy {
  const session = toolSessionOfEdit(tool);
  const router = InternalUrlRouter.instance();
  const specs = router.specs();
  const urlSchemes = [...specs.keys()];
  if (!urlSchemes.includes("https")) urlSchemes.push("https");
  const urlAliasSchemes: string[] = [];
  for (const [scheme, spec] of specs) if (spec.singleSlashAlias) urlAliasSchemes.push(scheme);
  const maxColumns = resolveOutputMaxColumns(session.settings);
  return {
    cwd: session.cwd,
    mode: tool.mode,
    allowFuzzy: cfgEditFuzzyMatch.get(session.settings),
    fuzzyThreshold: cfgEditFuzzyThreshold.get(session.settings),
    enforceSeenLines: cfgEditEnforceSeenLines.get(session.settings),
    maxColumns: maxColumns > 0 ? Math.min(maxColumns, DEFAULT_MAX_COLUMN) : DEFAULT_MAX_COLUMN,
    blockAutoGenerated: cfgEditBlockAutoGenerated.get(session.settings),
    planActive: session.getPlanModeState?.()?.enabled ?? false,
    urlSchemes,
    urlAliasSchemes,
    planWritableRoots: router.sandboxRoots(sessionResolveContext(session, { signal })),
    homeDir: os.homedir(),
    rawInput,
  };
}

function openRemoteEdit(tool: EditTool, rawInput: boolean, signal?: AbortSignal, onPreview?: (error: Error | null, batch: EditPreviewBatch) => void): RemoteEditOpen {
  const session = toolSessionOfEdit(tool);
  const state = { resolveContext: sessionResolveContext(session, { signal }) } as RemoteEditOpen;
  const native = new EditSession(
    getEditStore(session),
    remoteEditPolicy(tool, rawInput, signal),
    onPreview,
    async (_error, url): Promise<EditUrlResolution> => {
      const parsed = parseDocumentPath(url);
      if (parsed.kind === "invalid") return { error: parsed.message, planWritable: false };
      if (parsed.kind !== "octo") return { error: `Not an Octo document path: '${url}'`, planWritable: false };
      if (parsed.target.selector) return { error: `Hashline edits must target the whole Octo document: '${url}'`, planWritable: false };
      const sessionState = await runtime.sessionState(session);
      const document = sessionState.readDocuments.get(parsed.target.id);
      if (!document) return { error: `Read Octo document '${url}' before editing it`, planWritable: false };
      const filePath = await runtime.pathFor(sessionState, document);
      return { path: filePath, planWritable: false };
    },
  );
  state.native = native;
  return state;
}

function readOutputForOcto(result: NativeResult, filePath: string | undefined, displayPath: string): NativeResult {
  const content = result.content.map(block => ({ ...block }));
  const first = content.find(block => block.type === "text" && typeof block.text === "string");
  if (first && typeof first.text === "string") {
    const newline = first.text.indexOf("\n");
    const headerLine = newline < 0 ? first.text : first.text.slice(0, newline);
    const header = /^\[([^\]]+)#([0-9a-f]{4})\]$/i.exec(headerLine);
    if (header && (!filePath || header[1] === filePath || path.resolve(header[1]!) === path.resolve(filePath))) {
      first.text = `[${displayPath}#${header[2]}]${newline < 0 ? "" : first.text.slice(newline)}`;
    }
    if (result.isError && !first.text.includes(displayPath)) {
      first.text = `Unable to read Octo document '${displayPath}': ${first.text}`;
    }
  }
  const details = result.details && typeof result.details === "object" ? { ...(result.details as Record<string, unknown>) } : {};
  details.resolvedPath = displayPath;
  return { ...result, content, details };
}


const patchedReadExecute: typeof ReadTool.prototype.execute = async function (
  this: ReadTool,
  toolCallId,
  params,
  signal,
  onUpdate,
  context,
) {
  const session = toolSessionOfRead(this);
  const rawPath = typeof params.path === "string" ? params.path : "";
  const parsed = parseDocumentPath(rawPath);
  if (parsed.kind === "other" || !runtime.isActive(session)) {
    return nativeReadExecute.call(this, toolCallId, params, signal, onUpdate, context);
  }
  if (parsed.kind === "invalid") return toolError(parsed.message) as Awaited<ReturnType<typeof nativeReadExecute>>;
  if (parsed.target.source === "https") {
    return toolError(`HTTPS Octo URL '${rawPath}' must be normalized before native approval`) as Awaited<ReturnType<typeof nativeReadExecute>>;
  }

  const displayPath = runtime.displayPathFor(session, toolCallId, parsed.target.canonicalPath);
  try {
    const result = await nativeReadExecute.call(this, toolCallId, params, signal, onUpdate, context) as NativeResult;
    const state = await runtime.sessionState(session);
    return readOutputForOcto(result, state.filesById.get(parsed.target.id), displayPath) as Awaited<ReturnType<typeof nativeReadExecute>>;
  } catch (error) {
    return toolError(`Unable to read Octo document '${displayPath}': ${errorText(error)}`) as Awaited<ReturnType<typeof nativeReadExecute>>;
  }
};

function createRemoteStreamState(tool: EditTool, init: AgentToolArgStreamInit): EditStreamState {
  const state: EditStreamState = { tool, init, chunks: [], branch: "pending" };
  currentEditStreams(tool).set(init.toolCallId, state);
  return state;
}

function selectStreamBranch(state: EditStreamState, args?: unknown): void {
  if (state.branch !== "pending") return;
  const session = toolSessionOfEdit(state.tool);
  if (remoteStreamTarget(state.chunks, args)) {
    state.branch = state.tool.mode === "hashline" ? "remote" : "unsupported";
    if (state.branch === "remote") {
      state.remote = openRemoteEdit(
        state.tool,
        state.init.customWireName !== undefined,
        undefined,
        (error, batch) => {
          if (!error) state.init.emit(batch);
        },
      );
      for (const chunk of state.chunks) state.remote.native.push(chunk);
    }
    state.chunks.length = 0;
    return;
  }
  if (likelyLocalStreamTarget(state.chunks)) {
    state.branch = "native";
    state.nativeStream = nativeEditOpenArgStream.call(state.tool, state.init);
    for (const chunk of state.chunks) state.nativeStream.push(chunk);
    state.chunks.length = 0;
    return;
  }
  if (args !== undefined) {
    state.branch = "native";
    state.nativeStream = nativeEditOpenArgStream.call(state.tool, state.init);
    for (const chunk of state.chunks) state.nativeStream.push(chunk);
    state.chunks.length = 0;
    state.nativeStream.end(args);
    state.argsJson = JSON.stringify(args);
  }
}

const patchedEditOpenArgStream: typeof EditTool.prototype.openArgStream = function (
  this: EditTool,
  init,
) {
  const session = toolSessionOfEdit(this);
  if (!runtime.isActive(session)) return nativeEditOpenArgStream.call(this, init);
  const streams = currentEditStreams(this);
  const previous = streams.get(init.toolCallId);
  if (previous) closeStreamState(previous);
  const state = createRemoteStreamState(this, init);
  return {
    push(delta: string) {
      if (state.branch === "native") state.nativeStream?.push(delta);
      else if (state.branch === "remote") state.remote?.native.push(delta);
      else if (state.branch === "unsupported") return;
      else {
        state.chunks.push(delta);
        selectStreamBranch(state);
      }
    },
    end(args: unknown) {
      if (state.branch === "pending") selectStreamBranch(state, args);
      if (state.branch === "native") {
        if (!state.argsJson) state.nativeStream?.end(args);
        state.argsJson = JSON.stringify(args);
      } else if (state.branch === "remote") {
        state.remote?.native.finish();
        state.argsJson = JSON.stringify(args);
        if (state.remote) state.remote.argsJson = state.argsJson;
      } else {
        state.argsJson = JSON.stringify(args);
      }
    },
    cancel() {
      if (state.branch === "native") state.nativeStream?.cancel();
      else state.remote?.native.close();
      state.chunks.length = 0;
      if (streams.get(init.toolCallId) === state) streams.delete(init.toolCallId);
    },
  };
};

function remoteSectionsFor(input: string): { parsed: HashlineSections; local: HashlineSection[]; remote: HashlineSection[] } | undefined {
  const parsed = hashlineSections(input);
  if (!parsed) return undefined;
  const local: HashlineSection[] = [];
  const remote: HashlineSection[] = [];
  for (const section of parsed.sections) {
    const target = parseDocumentPath(section.path);
    if (target.kind === "octo" || target.kind === "invalid" && isOctoLikePath(section.path)) remote.push(section);
    else local.push(section);
  }
  return { parsed, local, remote };
}

function mapTempPaths(text: string, state: OctoSessionState): string {
  let result = text;
  for (const [id, filePath] of state.filesById) {
    result = result.replaceAll(filePath, `octo://${id}`);
  }
  return result;
}

async function applyRemoteEdit(
  tool: EditTool,
  toolCallId: string,
  input: string,
  signal: AbortSignal | undefined,
  streamed: EditStreamState | undefined,
): Promise<NativeResult> {
  const session = toolSessionOfEdit(tool);
  if (session.deviceOnlyWrite === true) return toolError("Octo edits are unavailable when write is device-only");
  const sections = hashlineSections(input);
  if (!sections) return toolError("Octo edits require hashline mode and a recent read snapshot");
  const remoteTargets = sections.sections.map(section => parseDocumentPath(section.path));
  for (const target of remoteTargets) {
    if (target.kind === "invalid") return toolError(target.message);
    if (target.kind !== "octo") return toolError("Octo edits require hashline mode and a recent read snapshot");
    if (target.target.selector) return toolError(`Hashline edits must target the whole Octo document: '${target.target.originalPath}'`);
  }

  try {
    for (const target of remoteTargets) {
      if (target.kind === "octo") {
        await enforcePlanModeWrite(session, target.target.canonicalBasePath, { op: "update", signal });
      }
    }
  } catch (error) {
    return toolError(errorText(error));
  }

  const remoteInput = [...sections.prefix, ...sections.sections.flatMap(section => section.lines), ...sections.suffix].join("\n");
  const argsJson = JSON.stringify({ input: remoteInput });
  let open: RemoteEditOpen | undefined;
  if (streamed?.branch === "remote" && streamed.remote && streamed.argsJson === argsJson) {
    open = streamed.remote;
    open.resolveContext.signal = signal;
  } else {
    streamed?.remote?.native.close();
    open = openRemoteEdit(tool, false, signal);
    open.native.setArgsJson(argsJson);
    open.native.finish();
  }
  if (streamed) {
    const streams = currentEditStreams(tool);
    if (streams.get(toolCallId) === streamed) streams.delete(toolCallId);
  }

  const state = await runtime.sessionState(session);
  const committed = new Map<string, { displayPath: string; canonicalPath: string }>();
  let outcome: EditApplyOutcome;
  try {
    outcome = await open.native.apply({ lspFlush: false }, async (error, request: EditWriteRequest) => {
      if (error) throw error;
      if (signal?.aborted) throw new Error("Octo edit was cancelled before submission");
      if (request.op !== "update" || request.content === undefined) {
        throw new Error(`Octo documents cannot be ${request.op === "delete" ? "deleted" : request.op === "move" ? "renamed" : "created"}`);
      }
      const id = runtime.idForFile(session, request.path);
      const document = id ? state.readDocuments.get(id) : undefined;
      if (!id || !document) throw new Error(`No read snapshot is available for '${request.displayPath}'`);
      const canonicalPath = `octo://${id}`;
      await enforcePlanModeWrite(session, canonicalPath, { op: "update", signal });
      const written = await writeDocument(document, request.content);
      committed.set(id, { displayPath: request.displayPath || canonicalPath, canonicalPath });
      await runtime.recordEdit(state, written);
      return { written: written.text };
    });
  } catch (error) {
    open.native.close();
    const committedPaths = [...committed.values()].map(item => runtime.displayPathFor(session, toolCallId, item.canonicalPath));
    return toolError(
      committedPaths.length > 0
        ? `Octo edit partially committed for ${committedPaths.join(", ")}; later operation failed: ${errorText(error)}`
        : `Octo edit failed: ${errorText(error)}`,
    );
  } finally {
    open.native.close();
  }

  const displayPaths = [...new Set([...committed.values()].map(item => runtime.displayPathFor(session, toolCallId, item.canonicalPath)))];
  let text = mapTempPaths(outcome.text || outcome.files.map(file => file.text).join("\n"), state);
  if (displayPaths.length > 0) {
    text = `Octo edit ${outcome.isError ? "partially applied or failed" : "completed"} for: ${displayPaths.join(", ")}\n${text}`;
  }
  const details = {
    files: outcome.files.map(file => {
      const id = runtime.idForFile(session, file.path);
      const canonical = id ? `octo://${id}` : file.displayPath;
      return {
        path: runtime.displayPathFor(session, toolCallId, canonical),
        operation: file.op,
        diff: file.diff,
      };
    }),
    ...(outcome.errorKind ? { errorKind: outcome.errorKind } : {}),
  };
  return {
    content: [{ type: "text", text }],
    details,
    ...(outcome.isError ? { isError: true } : {}),
  };
}

function nativeToolParamsForSections(params: Record<string, unknown>, input: string): Record<string, unknown> {
  return { ...params, input };
}

const patchedEditExecute: typeof EditTool.prototype.execute = async function (
  this: EditTool,
  toolCallId,
  params,
  signal,
  onUpdate,
  context,
) {
  const session = toolSessionOfEdit(this);
  const streams = currentEditStreams(this);
  const streamed = streams.get(toolCallId);
  const input = inputString(params);
  const directPath = pathString(params);
  const directTarget = directPath ? parseDocumentPath(unwrapWritePath(directPath).path) : { kind: "other" as const };
  const parsedSections = input ? remoteSectionsFor(input) : undefined;
  const hasRemoteSections = !!parsedSections?.remote.length;
  const nonHashlineTarget = input ? hasNonHashlineOctoFileTarget(input) : false;
  const hasRemoteDirectPath = directTarget.kind === "octo" || directTarget.kind === "invalid" && isOctoLikePath(directPath);

  if (!runtime.isActive(session) || (!hasRemoteSections && !nonHashlineTarget && !hasRemoteDirectPath)) {
    if (streamed) {
      if (streamed.branch === "remote" || streamed.branch === "unsupported") closeStreamState(streamed);
      if (streams.get(toolCallId) === streamed) streams.delete(toolCallId);
    }
    return nativeEditExecute.call(this, toolCallId, params, signal, onUpdate, context);
  }

  if (this.mode !== "hashline") {
    if (streamed) {
      closeStreamState(streamed);
      streams.delete(toolCallId);
    }
    return toolError("Octo edits require hashline mode and a recent read snapshot") as Awaited<ReturnType<typeof nativeEditExecute>>;
  }
  if (nonHashlineTarget || !parsedSections || !hasRemoteSections) {
    if (streamed) {
      closeStreamState(streamed);
      streams.delete(toolCallId);
    }
    return toolError("Octo edits require hashline mode and a recent read snapshot") as Awaited<ReturnType<typeof nativeEditExecute>>;
  }

  const localSections = parsedSections.local;
  const remoteSections = parsedSections.remote;
  if (localSections.length > 0 && hasCrossDomainRegisters(localSections, remoteSections)) {
    if (streamed) {
      closeStreamState(streamed);
      streams.delete(toolCallId);
    }
    return toolError("Named hashline registers cannot cross local and Octo documents in one edit") as Awaited<ReturnType<typeof nativeEditExecute>>;
  }

  if (localSections.length === 0) {
    return await applyRemoteEdit(this, toolCallId, input, signal, streamed) as Awaited<ReturnType<typeof nativeEditExecute>>;
  }

  const localInput = [...parsedSections.parsed.prefix, ...localSections.flatMap(section => section.lines), ...parsedSections.parsed.suffix].join("\n");
  const remoteInput = [...parsedSections.parsed.prefix, ...remoteSections.flatMap(section => section.lines), ...parsedSections.parsed.suffix].join("\n");
  let localResult: NativeResult;
  try {
    localResult = await nativeEditExecute.call(
      this,
      toolCallId,
      nativeToolParamsForSections(params as unknown as Record<string, unknown>, localInput),
      signal,
      onUpdate,
      context,
    ) as NativeResult;
  } catch (error) {
    localResult = toolError(`Native edit failed: ${errorText(error)}`);
  }
  const remoteResult = await applyRemoteEdit(this, toolCallId, remoteInput, signal, streamed);
  const remoteText = remoteResult.content
    .filter((block): block is { type: string; text: string } => typeof block.text === "string")
    .map(block => block.text)
    .join("\n");
  const localTargets = [...new Set(localSections.map(section => section.path))].join(", ");
  const remoteTargets = [...new Set(remoteSections.map(section => section.path))].map(raw => {
    const parsed = parseDocumentPath(raw);
    return parsed.kind === "octo" ? runtime.displayPathFor(session, toolCallId, parsed.target.canonicalBasePath) : raw;
  }).join(", ");
  const content = [
    { type: "text", text: `Local edit ${localResult.isError ? "returned an error" : "completed"} for: ${localTargets}` },
    ...localResult.content,
    { type: "text", text: `Octo edit ${remoteResult.isError ? "returned an error" : "completed"} for: ${remoteTargets}` },
    ...(remoteText ? [{ type: "text", text: remoteText }] : []),
  ];
  return {
    content,
    details: { local: localResult.details, remote: remoteResult.details },
    ...(localResult.isError || remoteResult.isError ? { isError: true } : {}),
  } as Awaited<ReturnType<typeof nativeEditExecute>>;
};

function normalizedInputForToolCall(event: { toolName: string; input: Record<string, unknown> }, aliases: Map<string, string>): { input?: Record<string, unknown>; error?: string; writeTag?: string } {
  const params = event.input;
  const next: Record<string, unknown> = { ...params };
  let changed = false;
  let writeTag: string | undefined;
  if (event.toolName === "read" || event.toolName === "write") {
    const rawPath = typeof params.path === "string" ? params.path : undefined;
    if (!rawPath) return {};
    const rewritten = replaceHttpPath(rawPath, aliases, event.toolName === "read");
    if (rewritten.error) return { error: rewritten.error };
    if (rewritten.path !== rawPath) {
      next.path = rewritten.path;
      changed = true;
    }
    writeTag = event.toolName === "write" ? rewritten.tag : undefined;
  } else if (event.toolName === "edit") {
    const rawPath = typeof params.path === "string" ? params.path : undefined;
    if (rawPath) {
      const rewritten = replaceHttpPath(rawPath, aliases, false);
      if (rewritten.error) return { error: rewritten.error };
      if (rewritten.path !== rawPath) {
        next.path = rewritten.path;
        changed = true;
      }
    }
    for (const key of ["input", "_input"] as const) {
      const rawInput = typeof params[key] === "string" ? (params[key] as string) : undefined;
      if (!rawInput) continue;
      const rewritten = rewriteHashlineInput(rawInput, aliases);
      if (rewritten.error) return { error: rewritten.error };
      if (rewritten.input !== rawInput) {
        next[key] = rewritten.input;
        changed = true;
      }
    }
    // Hashline compatibility fields are derived for approval only, not real tool parameters.
    if (Array.isArray(params.paths)) {
      delete next.paths;
      delete next.path;
      changed = true;
    }
  }
  return { ...(changed ? { input: next } : {}), ...(writeTag ? { writeTag } : {}) };
}

function installPrototypePatches(): void {
  const readPrototype = ReadTool.prototype as unknown as Record<PropertyKey, unknown>;
  if (!readPrototype[PATCH_MARKER]) {
    Object.defineProperty(readPrototype, PATCH_MARKER, { value: true });
    ReadTool.prototype.execute = patchedReadExecute;
  }
  const editPrototype = EditTool.prototype as unknown as Record<PropertyKey, unknown>;
  if (!editPrototype[PATCH_MARKER]) {
    Object.defineProperty(editPrototype, PATCH_MARKER, { value: true });
    EditTool.prototype.execute = patchedEditExecute;
    EditTool.prototype.openArgStream = patchedEditOpenArgStream;
  }
}

export function installNativeOctoTools(pi: ExtensionAPI): void {
  InternalUrlRouter.instance().register(octoProtocol);
  installPrototypePatches();

  pi.on("session_start", async (_event, context) => {
    await runtime.activateManager(context.sessionManager);
  });
  pi.on("session_switch", async (_event, context) => {
    await runtime.resetManager(context.sessionManager);
  });
  pi.on("session_shutdown", async (_event, context) => {
    await runtime.shutdownManager(context.sessionManager);
  });
  pi.on("before_agent_start", async (event, context) => {
    await runtime.activateManager(context.sessionManager);
    return event.systemPrompt.includes(EXTENSION_SESSION_PROMPT)
      ? undefined
      : { systemPrompt: [...event.systemPrompt, EXTENSION_SESSION_PROMPT] };
  });
  pi.on("tool_call", async (event, context) => {
    await runtime.activateManager(context.sessionManager);
    if (event.toolName !== "read" && event.toolName !== "write" && event.toolName !== "edit") return;
    const aliases = new Map<string, string>();
    const rewritten = normalizedInputForToolCall(event, aliases);
    if (rewritten.error) return { block: true, reason: rewritten.error };
    runtime.recordCall(context.sessionManager, event.toolCallId, aliases, rewritten.writeTag);
    return rewritten.input ? { input: rewritten.input } : undefined;
  });
  pi.on("tool_result", (_event, context) => {
    const manager = context.sessionManager;
    const active = (manager as ManagerRef).getSessionId?.() ?? (manager as ManagerRef).getSessionFile?.() ?? null;
    void active;
    // Result paths are rendered by the native read/edit wrappers and handler write response.
    // Drop the call record here; missing results are bounded by the manager's small FIFO cap.
    const managerState = runtime["#managerStateFor"];
    void managerState;
  });
}
