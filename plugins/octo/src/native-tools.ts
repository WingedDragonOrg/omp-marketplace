function canonicalExistingPath(filePath: string): string {
  try {
    return realpathSync(filePath);
  } catch {
    const parent = path.dirname(filePath);
    try {
      return path.join(realpathSync(parent), path.basename(filePath));
    } catch {
      return path.resolve(filePath);
    }
  }
}

function filePathAliases(filePath: string): string[] {
  const resolved = path.resolve(filePath);
  const canonical = canonicalExistingPath(filePath);
  const aliases = new Set([resolved, canonical]);
  for (const candidate of [resolved, canonical]) {
    if (candidate.startsWith("/private/")) aliases.add(candidate.slice("/private".length));
    else if (candidate.startsWith("/var/") || candidate.startsWith("/tmp/")) aliases.add(`/private${candidate}`);
  }
  return [...aliases];
}

function sameFilesystemPath(left: string, right: string, cwd: string): boolean {
  const expand = (value: string) => value === "~" ? os.homedir() : value.startsWith("~/") ? path.join(os.homedir(), value.slice(2)) : value;
  const leftAliases = new Set(filePathAliases(path.resolve(cwd, expand(left))));
  return filePathAliases(path.resolve(cwd, expand(right))).some(candidate => leftAliases.has(candidate));
}


function hashlineSections(input: string): HashlineSections | undefined {
  const lines = input.split(/\r?\n/);
  const starts: Array<{ index: number; path: string; tag: string }> = [];
  for (let index = 0; index < lines.length; index += 1) {
    const match = HASHLINE_HEADER.exec(lines[index]!);
    if (match) starts.push({ index, path: match[1]!, tag: match[2]!.toUpperCase() });
  }
  if (starts.length === 0) return undefined;
  const lastStart = starts[starts.length - 1]!.index;
  const endIndex = lines.findIndex((line, index) => index > lastStart && line.trim() === "*** End Patch");
  const bodyEnd = endIndex < 0 ? lines.length : endIndex;
  const sections = starts.map((start, index): HashlineSection => {
    const nextStart = starts[index + 1]?.index ?? bodyEnd;
    return { path: start.path, tag: start.tag, lines: lines.slice(start.index, Math.min(nextStart, bodyEnd)) };
  });
  return {
    prefix: lines.slice(0, starts[0]!.index),
    suffix: endIndex < 0 ? [] : lines.slice(endIndex),
    sections,
  };
}

function hasNonHashlineOctoFileTarget(input: string): boolean {
  return input.split(/\r?\n/).some(line => {
    const match = PATCH_FILE_HEADER.exec(line) ?? PATCH_MOVE_HEADER.exec(line);
    return !!match && isOctoLikePath(match[2]!.trim());
  });
}

function hasRemoteTargetInInput(input: string): boolean {
  const sections = hashlineSections(input);
  if (sections?.sections.some(section => isOctoLikePath(section.path))) return true;
  return hasNonHashlineOctoFileTarget(input);
}


function inputString(params: unknown): string {
  if (typeof params !== "object" || params === null) return "";
  const record = params as Record<string, unknown>;
  return typeof record.input === "string" ? record.input : typeof record._input === "string" ? record._input : "";
}

function pathString(params: unknown): string {
  if (typeof params !== "object" || params === null) return "";
  const pathValue = (params as Record<string, unknown>).path;
  return typeof pathValue === "string" ? pathValue : "";
}

function unwrapWritePath(rawPath: string): { path: string; tag?: string; wrapped: boolean } {
  const match = WRAPPED_WRITE_PATH.exec(rawPath);
  return match ? { path: match[1]!, tag: match[2]!.toUpperCase(), wrapped: true } : { path: rawPath, wrapped: false };
}

function replaceHttpPath(rawPath: string, aliases: Map<string, string>, allowSelector: boolean, allowTagWrapper = false): { path: string; error?: string; tag?: string } {
  const unwrapped = allowTagWrapper ? unwrapWritePath(rawPath) : { path: rawPath, wrapped: false as const };
  const parsed = parseDocumentPath(unwrapped.path);
  if (parsed.kind === "invalid" && parsed.source === "https") return { path: rawPath, error: parsed.message };
  if (parsed.kind !== "octo" || parsed.target.source !== "https") {
    return { path: rawPath, ...(unwrapped.tag ? { tag: unwrapped.tag } : {}) };
  }
  if (!allowSelector && parsed.target.selector) {
    return { path: rawPath, error: `Octo edits must target the whole document: '${rawPath}'` };
  }
  aliases.set(parsed.target.canonicalBasePath, parsed.target.originalBasePath);
  const canonical = parsed.target.canonicalPath;
  return {
    path: unwrapped.wrapped ? `[${canonical}#${unwrapped.tag}]` : canonical,
    ...(unwrapped.tag ? { tag: unwrapped.tag } : {}),
  };
}

function rewriteHashlineInput(input: string, aliases: Map<string, string>): { input: string; error?: string } {
  const lines = input.split(/\r?\n/);
  let changed = false;
  for (let index = 0; index < lines.length; index += 1) {
    const match = HASHLINE_HEADER.exec(lines[index]!);
    if (match) {
      const parsed = parseDocumentPath(match[1]!);
      if (parsed.kind === "invalid" && parsed.source === "https") return { input, error: parsed.message };
      if (parsed.kind === "octo" && parsed.target.source === "https") {
        if (parsed.target.selector) return { input, error: `Octo edits must target the whole document: '${match[1]}'` };
        aliases.set(parsed.target.canonicalBasePath, parsed.target.originalBasePath);
        lines[index] = lines[index]!.replace(match[1]!, parsed.target.canonicalBasePath);
        changed = true;
      }
      continue;
    }
    const fileHeader = PATCH_FILE_HEADER.exec(lines[index]!) ?? PATCH_MOVE_HEADER.exec(lines[index]!);
    if (!fileHeader) continue;
    const rewritten = replaceHttpPath(fileHeader[2]!.trim(), aliases, false);
    if (rewritten.error) return { input, error: rewritten.error };
    if (rewritten.path !== fileHeader[2]!.trim()) {
      lines[index] = `${fileHeader[1]}${rewritten.path}`;
      changed = true;
    }
  }
  return { input: changed ? lines.join("\n") : input };
}


function remoteStreamTarget(chunks: readonly string[], args?: unknown): boolean {
  const view = chunks.join("").replace(/\\n/g, "\n").replace(/\\r/g, "\r").replace(/\\"/g, '"');
  const paths = view.split(/\r?\n/).flatMap(line => {
    const hashline = HASHLINE_HEADER.exec(line);
    if (hashline) return [hashline[1]!];
    const patch = PATCH_FILE_HEADER.exec(line) ?? PATCH_MOVE_HEADER.exec(line);
    if (patch) return [patch[2]!.trim()];
    const jsonPath = /"(?:_?path)"\s*:\s*"([^"]+)"/i.exec(line);
    return jsonPath ? [jsonPath[1]!] : [];
  });
  if (paths.some(isOctoLikePath)) return true;
  if (args !== undefined) {
    const direct = pathString(args);
    if (direct && isOctoLikePath(unwrapWritePath(direct).path)) return true;
    const input = inputString(args);
    if (input && hasRemoteTargetInInput(input)) return true;
  }
  return false;
}

